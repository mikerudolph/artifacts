CREATE SCHEMA comparison;
SET search_path = comparison,pg_temp;
CREATE TABLE facts(id text PRIMARY KEY, repo_id int, state text, created_at timestamptz, expires_at timestamptz NOT NULL, revoked_at timestamptz);
CREATE TABLE effective(LIKE facts INCLUDING ALL);
ALTER TABLE effective ADD COLUMN invalid_at timestamptz NOT NULL;
INSERT INTO facts SELECT i::text, i%1000, CASE WHEN i%10=0 THEN 'revoked' ELSE 'active' END, now()-interval '1 day', CASE WHEN i<=50000 THEN now()-interval '10 days' ELSE now()+interval '1 day' END, CASE WHEN i%10=0 THEN now()-interval '9 days' END FROM generate_series(1,100000) i;
INSERT INTO effective SELECT *, LEAST(expires_at,revoked_at) FROM facts;
CREATE INDEX facts_cleanup_idx ON facts(LEAST(expires_at,revoked_at));
CREATE INDEX effective_cleanup_idx ON effective(invalid_at);
CREATE INDEX facts_repo_idx ON facts(repo_id,state);
ANALYZE facts;
ANALYZE effective;
SELECT 'backlog: timestamp facts';
EXPLAIN (ANALYZE,BUFFERS) SELECT id FROM facts WHERE LEAST(expires_at,revoked_at)<now()-interval '7 days' ORDER BY LEAST(expires_at,revoked_at) LIMIT 1000 FOR UPDATE SKIP LOCKED;
SELECT 'backlog: effective timestamp';
EXPLAIN (ANALYZE,BUFFERS) SELECT id FROM effective WHERE invalid_at<now()-interval '7 days' ORDER BY invalid_at LIMIT 1000 FOR UPDATE SKIP LOCKED;
UPDATE facts SET expires_at=now()+interval '1 day',revoked_at=NULL,state='active' WHERE id::int<99901;
UPDATE effective SET invalid_at=now()+interval '1 day' WHERE id::int<99901;
ANALYZE facts;
ANALYZE effective;
SELECT 'mostly valid: timestamp facts';
EXPLAIN (ANALYZE,BUFFERS) SELECT id FROM facts WHERE LEAST(expires_at,revoked_at)<now()-interval '7 days' ORDER BY LEAST(expires_at,revoked_at) LIMIT 1000 FOR UPDATE SKIP LOCKED;
SELECT 'mostly valid: effective timestamp';
EXPLAIN (ANALYZE,BUFFERS) SELECT id FROM effective WHERE invalid_at<now()-interval '7 days' ORDER BY invalid_at LIMIT 1000 FOR UPDATE SKIP LOCKED;
SELECT 'list all states';
EXPLAIN (ANALYZE,BUFFERS) SELECT * FROM facts WHERE repo_id=1 ORDER BY created_at DESC LIMIT 20;
SELECT 'count all states';
EXPLAIN (ANALYZE,BUFFERS) SELECT count(*) FROM facts WHERE repo_id=1;
SELECT 'list active';
EXPLAIN (ANALYZE,BUFFERS) SELECT * FROM facts WHERE repo_id=1 AND state='active' ORDER BY created_at DESC LIMIT 20;
SELECT 'count active';
EXPLAIN (ANALYZE,BUFFERS) SELECT count(*) FROM facts WHERE repo_id=1 AND state='active';
DROP SCHEMA comparison CASCADE;
